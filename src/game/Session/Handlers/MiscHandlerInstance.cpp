void instances::ResetInstances(Player& who, WorldPacket& )
{
    DEBUG_LOG("WORLD: Received opcode CMSG_RESET_INSTANCES");

    if (Group* pGroup = who.GetGroup())
    {
        if (pGroup->IsLeader(who.GetObjectGuid()))
        {
            pGroup->Binds().Reset(INSTANCE_RESET_ALL, &who);
        }
    }
    else
    {
        who.Binds().Reset(INSTANCE_RESET_ALL);
    }
}
